#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Opt-in workaround for OpenChamber inside magnusoverli/opencode.
# Put this file in <config>/opencode/startup.d/, enable Startup hooks (beta),
# and restart that add-on. It must run in the OpenCode/OpenChamber container,
# NOT in the Wyoming OpenAI Gateway container. See the adjacent README.
#
# Based on the repository owner's working hook. Publication guardrails keep
# the listener loopback-only, reject HTTP redirects, bound discovery responses,
# and probe declared TCP ports only. The first answering speech API wins.
#
# OpenChamber's add-on service uses env -i, so exporting its remote-URL opt-in
# from a separate startup hook cannot change that service's environment.
# This hook instead provides a local, fixed-target speech proxy.

set -euo pipefail
umask 077

APP_DIR=/data/openchamber-loopback-proxy
ENTRY="${APP_DIR}/proxy.mjs"
LOG="${APP_DIR}/proxy.log"

# Never use set -x: this hook's environment carries Supervisor credentials.
for tool in node setsid pgrep flock; do
    if ! command -v "${tool}" >/dev/null 2>&1; then
        echo "ERROR: required command is missing: ${tool}"
        exit 1
    fi
done
mkdir -p "${APP_DIR}"
exec 9>"${APP_DIR}/startup.lock"
if ! flock -n 9; then
    echo "Another loopback proxy hook is starting; check ${LOG} for readiness."
    exit 0
fi
if pgrep -f "${ENTRY}" >/dev/null 2>&1; then
    echo "Loopback proxy is already running."
    exit 0
fi

cat >"${ENTRY}" <<'PROXY_EOF'
// Generated by 10-openchamber-loopback-proxy.sh. Edit that hook, not this file.
import http from "node:http";
import { lookup } from "node:dns/promises";

const SUPERVISOR_URL = process.env.OPENCHAMBER_PROXY_SUPERVISOR_URL || "http://supervisor";
const SUPERVISOR_TOKEN = process.env.SUPERVISOR_TOKEN || "";
const LISTEN_HOST = process.env.OPENCHAMBER_PROXY_LISTEN_HOST || "127.0.0.1";
const PREFERRED_PORT = Number(process.env.OPENCHAMBER_PROXY_PORT || 8555);
const DNS_FAMILY = Number(process.env.OPENCHAMBER_PROXY_DNS_FAMILY || 4);
const TARGET_SLUG = process.env.OPENCHAMBER_PROXY_TARGET_SLUG || "";
const UPSTREAM_TIMEOUT_MS = Number(process.env.OPENCHAMBER_PROXY_UPSTREAM_TIMEOUT_MS ?? 300000);

const PROBE_TIMEOUT_MS = 2500;
const MAX_APPS = 64;
const MAX_PORTS_PER_APP = 8;
const MAX_METADATA_BYTES = 1024 * 1024;
const PROBE_CONCURRENCY = 16;
const DNS_TIMEOUT_MS = 5000;
let supervisorBase;
const log = (...args) => console.log(new Date().toISOString(), "[loopback-proxy]", ...args);
const validSlug = (slug) => /^[a-z0-9][a-z0-9_-]{0,63}$/.test(slug);
const dnsName = (slug) => slug.replace(/_/g, "-");

function trustedSupervisorOrigin(value) {
  let url;
  try { url = new URL(value); } catch { throw new Error("invalid Supervisor URL"); }
  const allowed = ["supervisor", "127.0.0.1", "localhost", "[::1]"];
  if (!["http:", "https:"].includes(url.protocol) || !allowed.includes(url.hostname)
      || url.username || url.password || url.pathname !== "/" || url.search || url.hash) {
    throw new Error("Supervisor URL must target supervisor or trusted loopback without credentials");
  }
  return url.origin;
}

async function lookupWithDeadline(host, options) {
  let timer;
  try {
    return await Promise.race([
      lookup(host, options),
      new Promise((_, reject) => {
        timer = setTimeout(() => reject(new Error("DNS lookup timed out")), DNS_TIMEOUT_MS);
      }),
    ]);
  } finally {
    clearTimeout(timer);
  }
}

async function boundedJSON(response) {
  const chunks = [];
  let size = 0;
  for await (const chunk of response.body) {
    size += chunk.length;
    if (size > MAX_METADATA_BYTES) throw new Error("discovery response too large");
    chunks.push(chunk);
  }
  try {
    return JSON.parse(Buffer.concat(chunks).toString("utf8"));
  } catch {
    // JSON parser diagnostics can echo response contents, including credentials.
    throw new Error("invalid JSON discovery response");
  }
}

async function supervisorJSON(path) {
  const ac = new AbortController();
  const timer = setTimeout(() => ac.abort(), 5000);
  try {
    const response = await fetch(`${supervisorBase}${path}`, {
      headers: SUPERVISOR_TOKEN ? { Authorization: `Bearer ${SUPERVISOR_TOKEN}` } : {},
      signal: ac.signal,
      redirect: "error",
    });
    if (!response.ok) throw new Error(`${path} -> HTTP ${response.status}`);
    const body = await boundedJSON(response);
    return body && typeof body === "object" && "data" in body ? body.data : body;
  } finally {
    clearTimeout(timer);
  }
}

// Use INTERNAL TCP port keys, never published host-port values. Supervisor's
// current info map is network; accept older ports and nested network.tcp too.
function portsOf(info) {
  const found = new Set();
  const take = (object, bareTCP = false) => {
    if (!object || typeof object !== "object" || Array.isArray(object)) return;
    for (const key of Object.keys(object)) {
      const match = String(key).match(bareTCP
        ? /^([1-9][0-9]{0,4})(?:\/tcp)?$/ : /^([1-9][0-9]{0,4})\/tcp$/);
      const port = match ? Number(match[1]) : 0;
      if (port > 0 && port <= 65535) found.add(port);
    }
  };
  take(info?.network);
  take(info?.ports);
  take(info?.network?.tcp, true);
  return [...found].slice(0, MAX_PORTS_PER_APP);
}

function selectedGatewayRoles(body, responseOK) {
  if (!body || typeof body !== "object" || Array.isArray(body)
      || !Object.hasOwn(body, "ready") || !Object.hasOwn(body, "tts")
      || !Object.hasOwn(body, "stt") || !body.gateway || typeof body.gateway !== "object"
      || Array.isArray(body.gateway)) return null;

  if (!responseOK || body.ready !== true || body.gateway.healthy !== true) return [];

  const selected = [];
  const supportsRole = (decision, capability) => decision?.status === "selected"
    && decision.provider && typeof decision.provider === "object"
    && Array.isArray(decision.provider.capabilities)
    && decision.provider.capabilities.includes(capability);
  if (supportsRole(body.tts, "tts")) selected.push("tts");
  if (supportsRole(body.stt, "asr")) selected.push("stt");
  return selected;
}

async function discoverSpeechRoles(host, port) {
  const ac = new AbortController();
  const timer = setTimeout(() => ac.abort(), PROBE_TIMEOUT_MS);
  try {
    try {
      const response = await fetch(`http://${host}:${port}/readyz`, {
        signal: ac.signal, redirect: "error",
      });
      const body = await boundedJSON(response);
      const roles = selectedGatewayRoles(body, response.ok);
      // A recognized gateway must prove its own readiness and selected roles;
      // /v1/voices is only a compatibility fallback for generic TTS services.
      if (roles !== null) return roles;
    } catch {
      // An optional readiness endpoint may be absent or malformed. Keep the
      // original candidate-wide deadline when trying the generic TTS fallback.
    }

    if (ac.signal.aborted) return [];
    const response = await fetch(`http://${host}:${port}/v1/voices`, {
      signal: ac.signal, redirect: "error",
    });
    if (!response.ok) return [];
    const body = await boundedJSON(response);
    return body && Array.isArray(body.voices) && body.voices.length ? ["tts"] : [];
  } catch {
    return [];
  } finally {
    clearTimeout(timer);
  }
}

async function listApps() {
  const problems = [];
  // New app API when permitted; legacy info inventory also works with the
  // default Supervisor role. A failed request may be 403 as well as 404.
  for (const [path, key] of [["/v2/apps", "apps"], ["/supervisor/info", "addons"]]) {
    try {
      const data = await supervisorJSON(path);
      if (Array.isArray(data?.[key])) {
        log(`listed apps via ${path}`);
        return data[key];
      }
      problems.push(`${path} returned no '${key}' array`);
    } catch (error) {
      problems.push(`${path}: ${error.message}`);
    }
  }
  throw new Error(`could not list apps - ${problems.join("; ")}`);
}

async function appInfo(slug) {
  const encoded = encodeURIComponent(slug);
  let last;
  for (const path of [`/v2/apps/${encoded}/info`, `/addons/${encoded}/info`]) {
    try {
      return await supervisorJSON(path);
    } catch (error) {
      last = error;
    }
  }
  throw last;
}

async function runningApps() {
  const apps = await listApps();
  return apps
    .filter((app) => app && typeof app.slug === "string" && validSlug(app.slug))
    .filter((app) => app.installed !== false && /^(started|running)$/i.test(String(app.state ?? "")))
    .filter((app) => !TARGET_SLUG || app.slug === TARGET_SLUG)
    .map((app) => app.slug)
    .slice(0, MAX_APPS);
}

async function candidates(slugs) {
  const out = [];
  let failures = 0;
  for (const slug of slugs) {
    let info;
    try {
      info = await appInfo(slug);
    } catch (error) {
      failures++;
      if (failures <= 2) log(`could not read info for ${slug}: ${error.message}`);
      continue;
    }
    const host = (Array.isArray(info?.dns) && typeof info.dns[0] === "string" && info.dns[0])
      || dnsName(slug);
    for (const port of portsOf(info)) out.push({ slug, host, port });
  }
  if (failures) log(`could not read info for ${failures} app(s) in total`);
  return out;
}

async function discover() {
  const slugs = await runningApps();
  log(`${slugs.length} installed app(s) are running`);
  const queue = await candidates(slugs);
  log(`probing ${queue.length} declared TCP port(s) across them`);
  let found = null;
  const worker = async () => {
    while (queue.length && !found) {
      const candidate = queue.shift();
      const roles = await discoverSpeechRoles(candidate.host, candidate.port);
      if (roles.length && !found) found = { ...candidate, roles };
    }
  };
  await Promise.all(Array.from({ length: PROBE_CONCURRENCY }, worker));
  return found;
}

function serve(target) {
  const server = http.createServer((req, res) => {
    const fail = (status, message) => {
      if (res.headersSent) { res.destroy(); return; }
      res.writeHead(status, { "content-type": "application/json" });
      res.end(JSON.stringify({ error: message }));
    };
    let upstream;
    let abandoned = false;
    res.on("close", () => { abandoned = true; upstream?.destroy(); });
    const options = DNS_FAMILY ? { family: DNS_FAMILY } : {};
    // Re-resolve for each request; container IP changes do not pin a stale IP.
    lookupWithDeadline(target.host, options).then(
      ({ address }) => {
        if (abandoned) return;
        upstream = http.request({
          host: address, port: target.port, method: req.method, path: req.url,
          headers: { ...req.headers, host: target.host }, timeout: UPSTREAM_TIMEOUT_MS,
        }, (response) => {
          res.writeHead(response.statusCode ?? 502, response.headers);
          response.on("error", () => fail(502, "upstream response failed"));
          response.pipe(res);
        });
        upstream.on("timeout", () => upstream.destroy(new Error("upstream timeout")));
        upstream.on("error", () => fail(502, "upstream request failed"));
        req.on("aborted", () => upstream.destroy());
        req.pipe(upstream);
      },
      () => fail(502, "cannot resolve upstream server"),
    );
  });

  let fellBack = false;
  server.on("listening", () => {
    const { port } = server.address();
    const visibleHost = LISTEN_HOST.includes(":") ? `[${LISTEN_HOST}]` : LISTEN_HOST;
    log(`listening on ${LISTEN_HOST}:${port} -> ${target.host}:${target.port}`);
    log(`Point the OpenChamber custom speech server at: http://${visibleHost}:${port}/v1`);
  });
  server.on("error", (error) => {
    if (error.code === "EADDRINUSE" && !fellBack) {
      fellBack = true;
      log(`port ${PREFERRED_PORT} is in use, taking a free port instead`);
      server.listen(0, LISTEN_HOST);
      return;
    }
    log(`cannot listen: ${error.code || "unknown error"}`);
    process.exit(1);
  });
  server.listen(PREFERRED_PORT, LISTEN_HOST);

  for (const signal of ["SIGTERM", "SIGINT"]) {
    process.on(signal, () => {
      server.close(() => process.exit(0));
      server.closeIdleConnections();
      setTimeout(() => { server.closeAllConnections(); process.exit(0); }, 5000).unref();
    });
  }
}

try {
  log("starting proxy discovery");
  if (!["127.0.0.1", "localhost", "::1"].includes(LISTEN_HOST)) {
    throw new Error("listener must stay on 127.0.0.1, localhost, or ::1");
  }
  if (!Number.isInteger(PREFERRED_PORT) || PREFERRED_PORT < 0 || PREFERRED_PORT > 65535) {
    throw new Error("invalid proxy port");
  }
  if (!Number.isInteger(UPSTREAM_TIMEOUT_MS)
      || UPSTREAM_TIMEOUT_MS < 1000 || UPSTREAM_TIMEOUT_MS > 300000) {
    throw new Error("upstream timeout must be an integer from 1000 to 300000 milliseconds");
  }
  if (![0, 4, 6].includes(DNS_FAMILY)) throw new Error("invalid DNS family");
  if (TARGET_SLUG && !validSlug(TARGET_SLUG)) throw new Error("invalid target app slug");
  supervisorBase = trustedSupervisorOrigin(SUPERVISOR_URL);
  if (!SUPERVISOR_TOKEN) throw new Error("SUPERVISOR_TOKEN is not set; run inside the add-on hook");
  const target = await discover();
  if (!target) {
    log("No running app reported a ready speech gateway or a nonempty /v1/voices list.");
    log("Start the gateway and its provider(s), wait for readiness, then re-run this hook.");
    process.exit(1);
  }
  const roleNames = target.roles.map((role) => role.toUpperCase()).join(", ");
  log(`using ${target.slug} (${target.host}:${target.port}); roles: ${roleNames}`);
  serve(target);
} catch (error) {
  log(`discovery failed: ${error.message}`);
  process.exit(1);
}
PROXY_EOF

setsid node "${ENTRY}" 9>&- >>"${LOG}" 2>&1 </dev/null &

# This is a process check, not readiness: large inventories take longer to probe.
sleep 3
if ! pgrep -f "${ENTRY}" >/dev/null 2>&1; then
    echo "ERROR: the proxy did not start. Its log is ${LOG}"
    tail -n 12 "${LOG}" 2>/dev/null | sed 's/^/    /'
    exit 1
fi

echo "Loopback proxy process started. Wait for the listening URL in ${LOG}"
tail -n 12 "${LOG}" 2>/dev/null | sed 's/^/    /'
